// Pick a logical variant from a phrase entry. Single strings return as-is.
// Arrays are randomly sampled, giving the translator a ~20% feel of variance
// while every option is hand-written to fit the input phrase.
function pickVariant(value: PhraseValue): string {
  if (Array.isArray(value)) {
    return value[Math.floor(Math.random() * value.length)];
  }
  return value;
}

export function translate(text: string, direction: Direction, ageGroup: AgeGroup): string {
  const dict = translations[direction][ageGroup];
  const trimmed = text.trim();

  if (dict[trimmed]) {
    return pickVariant(dict[trimmed]);
  }

  const lower = trimmed.toLowerCase();
  for (const [key, value] of Object.entries(dict)) {
    if (key.toLowerCase() === lower) {
      return pickVariant(value);
    }
  }

  for (const [key, value] of Object.entries(dict)) {
    if (lower.includes(key.toLowerCase())) {
      return pickVariant(value);
    }
  }

  const genericResponses: Record<Direction, string[]> = {
    menToWomen: [
      `"${trimmed}" — Translation: This is clearly a test and I'm already failing it`,
      `"${trimmed}" — Translation: I've thought about this exactly once and that was just now`,
      `"${trimmed}" — Translation: I'm expressing something, I'm just not sure what yet`,
      `"${trimmed}" — Translation: There are subtext levels here I haven't even discovered yet`,
      `"${trimmed}" — Translation: I said the words. What happens next is not my department.`,
      `"${trimmed}" — Translation: I meant something by this. I'll let you figure out which thing.`,
    ],
    womenToMen: [
      `"${trimmed}" — Translation: This means something. I'm just not sure what to do about it yet`,
      `"${trimmed}" — Translation: I should probably ask a follow-up question but I don't know which one`,
      `"${trimmed}" — Translation: Everything is fine and also not fine simultaneously`,
      `"${trimmed}" — Translation: I need more data before I can process this properly`,
      `"${trimmed}" — Translation: I've been given a clue. The puzzle is still assembling itself.`,
      `"${trimmed}" — Translation: There is definitely a right answer to this. I just don't know what it is.`,
    ],
  };

  const options = genericResponses[direction];
  return options[Math.floor(Math.random() * options.length)];
}
